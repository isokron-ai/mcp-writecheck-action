#!/usr/bin/env node
/**
 * Third-party corpus driver: runs mcp-writecheck against one shard of the corpus target list.
 * The same script runs in the public nightly workflow (lane `ci`) and on IsoKron's own machine for
 * the long tail (lane `mac`), and writes the same record format in both places.
 *
 *   node corpus/run-shard.mjs --targets T.json --cli DIR --out DIR [--work DIR] [--lane ci|mac]
 *                             [--shard N --shards M] [--only ID,ID] [--cli-commit SHA]
 *
 * Public-output rule (the corpus is not a findings channel): stdout and stderr carry only
 *
 *     automated candidate, unreviewed: not a finding
 *     run finished, exit N
 *
 * one "run finished" line per target, in shard order, with no target name, no verdict and no
 * record line. Everything else (install logs, backend logs, the CLI's own output, the server's
 * output, results.json, report.md, the ledger, metadata) goes to files under --out, which the
 * workflow encrypts to the archive's public key before upload.
 *
 * N is the public exit of that target, never a verdict:
 *     0   the CLI ran to completion (CLI exit 0 or 1: exit 1 is a violated MUST, a verdict, so it
 *         is folded to 0 here; the real exit is in the encrypted metadata)
 *     2, 3, 4, 130   the CLI's own usage/manifest error, refusal, stopped run, interruption
 *     70  the CLI crashed (killed by a signal, or an exit status the CLI does not document)
 *     124 the target hit its time limit
 *     125 harness error (download, checksum, install, backend, set-up, this script)
 * A CLI problem already recorded for a target in the list (`expect`) reports 0 and is kept in the
 * metadata as expected_cli_error; any other problem keeps its code.
 * The process exits 0 when every target's public exit is 0, and 1 otherwise: only our tool or
 * the harness turns a run red, never a target's verdict.
 */

import { spawn } from 'node:child_process';
import { createHash } from 'node:crypto';
import { cpSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync, createWriteStream } from 'node:fs';
import { arch, platform, release } from 'node:os';
import { dirname, join, resolve } from 'node:path';

export const LABEL = 'automated candidate, unreviewed: not a finding';
export const RUN_FORMAT = 'isokron-corpus-run/1';
export const TARGETS_FORMAT = 'isokron-corpus-targets/1';
const CLI_DOCUMENTED = new Set([0, 1, 2, 3, 4, 130]);
const say = (line) => process.stdout.write(`${line}\n`);

/** The public exit of one target (see the header). Pure; unit-tested. */
export function publicExit(t) {
  if (t.status === 'timeout') return 124;
  if (t.status === 'harness_error') return 125;
  if (t.status === 'cli_crash') return 70;
  if (t.status === 'cli_error') return CLI_DOCUMENTED.has(t.cli_exit) ? t.cli_exit : 70;
  return 0; // completed, or expected_cli_error (a known CLI problem recorded in the target list)
}

/** Classify one CLI step: completed (0/1), cli_error (2/3/4/130), cli_crash (signal or undocumented). */
export function classifyCli(step) {
  if (step.timed_out) return 'timeout';
  if (step.spawn_error) return 'harness_error';
  if (step.signal || step.exit === null) return 'cli_crash';
  if (step.exit === 0 || step.exit === 1) return 'completed';
  if (CLI_DOCUMENTED.has(step.exit)) return 'cli_error';
  return 'cli_crash';
}

/** `{{name}}` templates in strings, arrays and objects. Unknown names are an error (harness). */
export function fill(v, vars) {
  if (typeof v === 'string') {
    return v.replace(/\{\{([a-zA-Z0-9_]+)\}\}/g, (_, k) => {
      if (!(k in vars)) throw new HarnessError(`template variable ${k} is not set`);
      return String(vars[k]);
    });
  }
  if (Array.isArray(v)) return v.map((x) => fill(x, vars));
  if (v && typeof v === 'object') return Object.fromEntries(Object.entries(v).map(([k, x]) => [k, fill(x, vars)]));
  return v;
}

/** The generic catalog manifest: the server block and a stub resource (catalog mode calls no tool). */
export function catalogManifest(command, envNames, confirm) {
  const q = (s) => JSON.stringify(s);
  return [
    '# Generated by corpus/run-shard.mjs: catalog and plan only. The stub resource is never called;',
    '# catalog mode reads tools/list and calls no tool. A full run needs a hand-written manifest.',
    'mws: "0.9"',
    'server:',
    `  stdio: [${command.map(q).join(', ')}]`,
    `  env_passthrough: [${envNames.map(q).join(', ')}]`,
    '  processes: separate',
    'target:',
    '  environment: test',
    `  confirm: ${q(confirm)}`,
    'resources:',
    '  - name: catalogstub',
    '    read: { tool: mwsc_catalog_stub, args: { id: "{{id}}" } }',
    '    fixture: { id: mwsc-catalog-stub, name: mwsc-catalog-stub }',
    '    cleanup: leave',
    '',
  ].join('\n');
}

class HarnessError extends Error {}

function args(argv) {
  const o = { lane: 'ci', shard: 1, shards: 1, only: null, work: null, cliCommit: null, consumeTargets: false };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    const v = () => {
      if (i + 1 >= argv.length) throw new HarnessError(`${a} needs a value`);
      return argv[++i];
    };
    if (a === '--targets') o.targets = v();
    else if (a === '--cli') o.cli = v();
    else if (a === '--out') o.out = v();
    else if (a === '--work') o.work = v();
    else if (a === '--lane') o.lane = v();
    else if (a === '--shard') o.shard = Number(v());
    else if (a === '--shards') o.shards = Number(v());
    else if (a === '--only') o.only = v().split(',').filter(Boolean);
    else if (a === '--cli-commit') o.cliCommit = v();
    else if (a === '--consume-targets') o.consumeTargets = true;
    else throw new HarnessError(`unknown option ${a}`);
  }
  for (const k of ['targets', 'cli', 'out']) if (!o[k]) throw new HarnessError(`--${k} is required`);
  if (!(o.shard >= 1 && o.shard <= o.shards)) throw new HarnessError('--shard must be between 1 and --shards');
  return o;
}

const sha256File = (f) => createHash('sha256').update(readFileSync(f)).digest('hex');
const sha256Text = (s) => createHash('sha256').update(s).digest('hex');
const now = () => new Date().toISOString();

/**
 * Run a command with all output to a log file, in its own process group, bounded by `deadline`
 * (ms since epoch). Never throws; returns { exit, signal, timed_out, spawn_error, ms, stdout }.
 */
function run(cmd, argv, { cwd, env, log, deadline, keepStdout = false, input = null }) {
  return new Promise((done) => {
    const t0 = Date.now();
    const out = createWriteStream(log, { flags: 'a' });
    out.write(`\n$ ${[cmd, ...argv].join(' ')}\n# cwd ${cwd} at ${now()}\n`);
    let stdout = '';
    let child;
    try {
      child = spawn(cmd, argv, { cwd, env, stdio: [input === null ? 'ignore' : 'pipe', 'pipe', 'pipe'], detached: true });
    } catch (e) {
      out.end(`# spawn error: ${e.message}\n`);
      return done({ exit: null, signal: null, timed_out: false, spawn_error: e.message, ms: 0, stdout: '' });
    }
    if (input !== null) child.stdin.end(input);
    child.stdout.on('data', (c) => {
      if (keepStdout) stdout += c;
      out.write(c);
    });
    child.stderr.on('data', (c) => out.write(c));
    let timedOut = false;
    const left = Math.max(1000, deadline - Date.now());
    const timer = setTimeout(() => {
      timedOut = true;
      try { process.kill(-child.pid, 'SIGTERM'); } catch {}
      setTimeout(() => { try { process.kill(-child.pid, 'SIGKILL'); } catch {} }, 15_000).unref();
    }, left);
    let spawnError = null;
    child.on('error', (e) => { spawnError = e.message; });
    child.on('close', (code, signal) => {
      clearTimeout(timer);
      // Anything the step left behind in its process group (a server's child, a helper) dies with it:
      // an orphan would outlive the job and the runner prints its process name in the public log.
      try { process.kill(-child.pid, 'SIGKILL'); } catch {}
      out.end(`# exit ${code} signal ${signal}${timedOut ? ' (time limit)' : ''} after ${Date.now() - t0} ms\n`);
      done({ exit: code, signal, timed_out: timedOut, spawn_error: spawnError, ms: Date.now() - t0, stdout });
    });
  });
}

async function must(step, what) {
  const r = await step;
  if (r.timed_out) throw Object.assign(new HarnessError(`${what}: time limit`), { timeout: true });
  if (r.spawn_error || r.exit !== 0) throw new HarnessError(`${what}: exit ${r.exit} signal ${r.signal} ${r.spawn_error ?? ''}`.trim());
  return r;
}

async function download(url, file, sha256, log) {
  let buf;
  if (url.startsWith('file://')) buf = readFileSync(new URL(url)); // local artifacts (tests, a mirror)
  else {
    const res = await fetch(url, { redirect: 'follow' });
    if (!res.ok) throw new HarnessError(`download: HTTP ${res.status}`);
    buf = Buffer.from(await res.arrayBuffer());
  }
  const got = createHash('sha256').update(buf).digest('hex');
  writeFileSync(log, `download ${url}\nsha256 ${got}\n`, { flag: 'a' });
  if (got !== sha256) throw new HarnessError(`checksum: artifact sha256 ${got} is not the pinned ${sha256}`);
  writeFileSync(file, buf);
  return got;
}

/** One target. Returns its metadata record; never throws. */
async function runTarget(t, o, ctx) {
  const tdir = resolve(o.work, t.id);
  const odir = resolve(o.out, t.id);
  rmSync(tdir, { recursive: true, force: true });
  mkdirSync(tdir, { recursive: true });
  mkdirSync(join(odir, 'logs'), { recursive: true });
  const L = (n) => join(odir, 'logs', `${n}.log`);
  const timeoutS = t.timeout_s ?? ctx.defaults.timeout_s ?? 600;
  const deadline = Date.now() + timeoutS * 1000;
  const meta = {
    format: RUN_FORMAT,
    label: LABEL,
    target: {
      id: t.id, name: t.name, ecosystem: t.ecosystem, package: t.package, version: t.version,
      artifact: t.artifact ?? null, source: t.source ?? null, license: t.license ?? null,
      manifest_kind: t.full ? 'hand-written (full)' : 'generic catalog',
    },
    cli: ctx.cli,
    spec: ctx.spec,
    runner: ctx.runner,
    github: ctx.github,
    lane: o.lane,
    started: now(),
    ended: null,
    timeout_s: timeoutS,
    artifact_sha256_verified: null,
    backends: [],
    deps: null,
    manifest_sha256: null,
    init_draft_sha256: null,
    steps: [],
    status: 'completed',
    cli_exit: null,
    harness_error: null,
    results: [],
  };
  const containers = [];
  const vars = { tdir, host: '127.0.0.1' };
  // Target-controlled processes (install, set-up, CLI, server) get an allowlisted environment: no
  // GITHUB_ENV/GITHUB_PATH/GITHUB_OUTPUT/GITHUB_STEP_SUMMARY (an honest tool that sees GitHub Actions
  // can write the public summary or later steps' env), no ACTIONS_*/RUNNER_*, no tokens, and a HOME
  // and package caches of their own, so one target cannot poison the next one's npm or pip cache.
  // Docker calls are ours and keep the driver's environment (dockerEnv).
  const home = join(tdir, 'home');
  mkdirSync(home, { recursive: true });
  const keep = ['PATH', 'LANG', 'LC_ALL', 'TZ', 'CORPUS_PYTHON'];
  const baseEnv = {
    ...Object.fromEntries(keep.filter((k) => process.env[k] !== undefined).map((k) => [k, process.env[k]])),
    HOME: home, TMPDIR: join(tdir, 'tmp'), XDG_CACHE_HOME: join(home, '.cache'), XDG_CONFIG_HOME: join(home, '.config'),
    npm_config_cache: join(home, '.npm'), PIP_CACHE_DIR: join(home, '.cache', 'pip'), UV_CACHE_DIR: join(home, '.cache', 'uv'),
    NO_COLOR: '1', npm_config_update_notifier: 'false', DO_NOT_TRACK: '1', CORPUS_SANDBOX: '1',
  };
  mkdirSync(baseEnv.TMPDIR, { recursive: true });
  const dockerEnv = process.env;
  try {
    // 1. The artifact, checked against the pinned sha256, then installed.
    if (t.ecosystem === 'npm') {
      const file = join(tdir, 'artifact.tgz');
      meta.artifact_sha256_verified = await download(t.artifact.url, file, t.artifact.sha256, L('install'));
      mkdirSync(join(tdir, 'pkg'));
      writeFileSync(join(tdir, 'pkg', 'package.json'), '{"private":true}\n');
      // npm_before: dependencies resolve as of that date (npm's --before), so a pinned target keeps
      // the same dependency tree night after night; deps.json records the tree that was installed.
      const before = t.npm_before ? [`--before=${t.npm_before}`] : [];
      await must(run('npm', ['install', '--no-audit', '--no-fund', '--loglevel=error', ...before, file], { cwd: join(tdir, 'pkg'), env: baseEnv, log: L('install'), deadline }), 'npm install');
      const ls = await run('npm', ['ls', '--all', '--json'], { cwd: join(tdir, 'pkg'), env: baseEnv, log: L('deps'), deadline, keepStdout: true });
      writeFileSync(join(odir, 'deps.json'), ls.stdout);
      meta.deps = { file: 'deps.json', sha256: sha256Text(ls.stdout) };
      vars.bin = join(tdir, 'pkg', 'node_modules', '.bin');
      vars.pkgdir = join(tdir, 'pkg', 'node_modules', t.package);
    } else if (t.ecosystem === 'pypi') {
      const file = join(tdir, t.artifact.file);
      meta.artifact_sha256_verified = await download(t.artifact.url, file, t.artifact.sha256, L('install'));
      const py = ctx.python;
      if (py.uv) await must(run('uv', ['venv', '--quiet', '--python', py.version, join(tdir, 'venv')], { cwd: tdir, env: baseEnv, log: L('install'), deadline }), 'venv');
      else await must(run(py.exe, ['-m', 'venv', join(tdir, 'venv')], { cwd: tdir, env: baseEnv, log: L('install'), deadline }), 'venv');
      const vpy = join(tdir, 'venv', 'bin', 'python');
      // constraints: the dependency versions recorded when the target was pinned (pip freeze), so
      // the tree does not drift; a package a platform does not install is simply not constrained.
      const cons = [];
      if (t.constraints?.length) {
        writeFileSync(join(tdir, 'constraints.txt'), t.constraints.join('\n') + '\n');
        cons.push('-c', join(tdir, 'constraints.txt'));
      }
      if (py.uv) await must(run('uv', ['pip', 'install', '--quiet', '--python', vpy, ...cons, file], { cwd: tdir, env: baseEnv, log: L('install'), deadline }), 'pip install');
      else await must(run(vpy, ['-m', 'pip', 'install', '--quiet', '--disable-pip-version-check', ...cons, file], { cwd: tdir, env: baseEnv, log: L('install'), deadline }), 'pip install');
      const fr = py.uv
        ? await run('uv', ['pip', 'freeze', '--python', vpy], { cwd: tdir, env: baseEnv, log: L('deps'), deadline, keepStdout: true })
        : await run(vpy, ['-m', 'pip', 'freeze', '--all'], { cwd: tdir, env: baseEnv, log: L('deps'), deadline, keepStdout: true });
      writeFileSync(join(odir, 'deps.txt'), fr.stdout);
      meta.deps = { file: 'deps.txt', sha256: sha256Text(fr.stdout) };
      vars.bin = join(tdir, 'venv', 'bin');
    } else if (t.ecosystem === 'binary') {
      const a = t.artifact[`${platform()}-${arch()}`];
      if (!a) throw new HarnessError(`no artifact for ${platform()}-${arch()}`);
      const file = join(tdir, a.file);
      meta.artifact_sha256_verified = await download(a.url, file, a.sha256, L('install'));
      mkdirSync(join(tdir, 'bin'));
      await must(run('tar', ['-xzf', file, '-C', join(tdir, 'bin')], { cwd: tdir, env: baseEnv, log: L('install'), deadline }), 'unpack');
      vars.bin = join(tdir, 'bin');
    } else throw new HarnessError(`unknown ecosystem ${t.ecosystem}`);

    // 2. Backends in containers, published on loopback ports Docker chooses.
    for (const [i, b] of (t.backends ?? []).entries()) {
      const name = `mwsv-corpus-${ctx.runId}-${t.id}-${i}`;
      const dargs = ['run', '-d', '--name', name, '-p', `127.0.0.1::${b.port}`];
      for (const [k, v] of Object.entries(fill(b.env ?? {}, vars))) dargs.push('-e', `${k}=${v}`);
      dargs.push(b.image, ...fill(b.args ?? [], vars));
      containers.push(name);
      await must(run('docker', dargs, { cwd: tdir, env: dockerEnv, log: L(`backend-${i}`), deadline }), `backend ${i} start`);
      const p = await must(run('docker', ['port', name, `${b.port}/tcp`], { cwd: tdir, env: dockerEnv, log: L(`backend-${i}`), deadline, keepStdout: true }), `backend ${i} port`);
      const port = p.stdout.trim().split('\n')[0].split(':').pop();
      vars[`port${i}`] = port;
      const ins = await run('docker', ['image', 'inspect', '--format', '{{json .RepoDigests}}', b.image], { cwd: tdir, env: dockerEnv, log: L(`backend-${i}`), deadline, keepStdout: true });
      meta.backends.push({ image: b.image, repo_digests: safeJson(ins.stdout), container_port: b.port });
      const waitUntil = Math.min(deadline, Date.now() + (b.wait_timeout_s ?? 120) * 1000);
      let ok = !b.wait;
      while (!ok && Date.now() < waitUntil) {
        const w = await run('docker', ['exec', name, ...fill(b.wait, vars)], { cwd: tdir, env: dockerEnv, log: L(`backend-${i}`), deadline });
        ok = w.exit === 0;
        if (!ok) await new Promise((r) => setTimeout(r, 2000));
      }
      if (!ok) throw new HarnessError(`backend ${i} not ready`);
      for (const s of b.setup ?? []) {
        const r = await must(run('docker', ['exec', ...(s.user ? ['-u', s.user] : []), name, ...fill(s.exec, vars)], { cwd: tdir, env: dockerEnv, log: L(`backend-${i}`), deadline, keepStdout: !!s.capture }), `backend ${i} set-up`);
        if (s.capture) vars[s.capture] = r.stdout.trim().split('\n').pop();
      }
    }

    // 3. Set-up in the target's work folder (data folders, a git repository, seed files).
    for (const line of t.setup ?? []) {
      await must(run('sh', ['-c', fill(line, vars)], { cwd: tdir, env: { ...baseEnv, TDIR: tdir }, log: L('setup'), deadline }), 'set-up');
    }

    // 4. The manifests: the init draft (archived as data), then the one the CLI runs.
    const command = fill(t.server.command, vars);
    const senv = fill(t.server.env ?? {}, vars);
    const cliEnv = { ...baseEnv, ...senv };
    const cliStep = async (name, argv) => {
      const r = await run(process.execPath, [ctx.cliEntry, ...argv], { cwd: tdir, env: cliEnv, log: L(name), deadline, keepStdout: true });
      const step = { step: name, exit: r.exit, signal: r.signal, timed_out: r.timed_out, spawn_error: r.spawn_error, ms: r.ms };
      meta.steps.push(step);
      return { r, step };
    };
    if (t.init !== false) {
      const { step } = await cliStep('init', ['init', '--out', join(tdir, 'init-draft.yaml'), ...Object.keys(senv).flatMap((k) => ['--env', k]), '--', ...command]);
      if (existsSync(join(tdir, 'init-draft.yaml'))) {
        cpSync(join(tdir, 'init-draft.yaml'), join(odir, 'init-draft.yaml'));
        meta.init_draft_sha256 = sha256File(join(odir, 'init-draft.yaml'));
      }
      step.informational = true; // init's result is data: a draft that fails is recorded, not judged
    }
    const manifestText = t.full?.manifest ? fill(t.full.manifest, vars) : catalogManifest(command, Object.keys(senv), `mwsv-corpus-${t.id}`);
    const manifest = join(tdir, 'writecheck.yaml');
    writeFileSync(manifest, manifestText);
    writeFileSync(join(odir, 'writecheck.yaml'), manifestText);
    meta.manifest_sha256 = sha256Text(manifestText);

    // 5. plan, catalog, and full where a person accepted the plan hash. The first CLI step that does
    //    not complete decides the target's status; later steps still run when they can.
    const decisive = [];
    const plan = await cliStep('plan', ['plan', '-m', manifest]);
    meta.plan_hash = (/^plan hash: ([0-9a-f]{16})$/m.exec(plan.r.stdout) ?? [])[1] ?? null;
    decisive.push(plan.step);
    const cat = await cliStep('catalog', ['catalog', '-m', manifest, '--out', join(tdir, 'results')]);
    decisive.push(cat.step);
    if (t.full && t.full.plan_hash) {
      if (meta.plan_hash !== t.full.plan_hash) {
        meta.plan_drift = { accepted: t.full.plan_hash, seen: meta.plan_hash };
      } else {
        const full = await cliStep('full', ['run', '-m', manifest, '--confirm-target', t.full.confirm, '--plan-hash', t.full.plan_hash, '--out', join(tdir, 'results'), '--state', join(tdir, 'state')]);
        decisive.push(full.step);
      }
    }
    for (const s of decisive) {
      const c = classifyCli(s);
      if (c !== 'completed') {
        meta.status = c;
        meta.cli_exit = s.exit;
        meta.failed_step = s.step;
        break;
      }
      meta.cli_exit = Math.max(meta.cli_exit ?? 0, s.exit ?? 0);
    }
    // A known CLI problem on this target (t.expect: { step, exit, error: regex, issue }) is recorded
    // as expected and does not turn the shard red, so a new problem stays visible; when it stops
    // happening the target is marked for the expectation to be removed (the dogfood pattern).
    if (t.expect) {
      const lg = join(odir, 'logs', `${t.expect.step}.log`);
      const err = existsSync(lg) ? ([...readFileSync(lg, 'utf8').matchAll(/^error: .*$/gm)].pop()?.[0] ?? '') : '';
      const hit = meta.failed_step === t.expect.step && meta.cli_exit === t.expect.exit && new RegExp(t.expect.error).test(err);
      if (hit) meta.status = 'expected_cli_error';
      else if (meta.status === 'completed') meta.expectation_flipped = t.expect.issue ?? true;
      meta.expect = t.expect;
    }
  } catch (e) {
    meta.status = e.timeout ? 'timeout' : 'harness_error';
    meta.harness_error = String(e.message ?? e);
  } finally {
    for (const c of containers) {
      const lg = L('backend-teardown');
      await run('docker', ['logs', c], { cwd: tdir, env: process.env, log: lg, deadline: Date.now() + 60_000 });
      await run('docker', ['rm', '-f', '-v', c], { cwd: tdir, env: process.env, log: lg, deadline: Date.now() + 60_000 });
    }
    // Results: every folder the CLI wrote, unchanged, plus the state (ledger) folder of a full run.
    for (const sub of ['results', 'state']) {
      const d = join(tdir, sub);
      if (existsSync(d)) cpSync(d, join(odir, sub), { recursive: true });
    }
    if (existsSync(join(odir, 'results'))) {
      for (const r of readdirSync(join(odir, 'results'))) {
        const f = join(odir, 'results', r, 'results.json');
        if (existsSync(f)) meta.results.push({ folder: `results/${r}`, sha256: sha256File(f), status: safeJson(readFileSync(f, 'utf8'))?.run?.status ?? null });
      }
    }
    meta.public_exit = publicExit(meta);
    meta.ended = now();
    writeFileSync(join(odir, 'meta.json'), JSON.stringify(meta, null, 2) + '\n');
    if (!ctx.keepWork) rmSync(tdir, { recursive: true, force: true });
  }
  return meta;
}

function safeJson(s) {
  try { return JSON.parse(s); } catch { return null; }
}

async function context(o) {
  const cliDir = resolve(o.cli);
  const cliEntry = join(cliDir, 'dist', 'src', 'cli', 'main.js');
  if (!existsSync(cliEntry)) throw new HarnessError('the CLI entry script is missing');
  const sink = join(o.out, '_shard', 'context.log');
  const dl = Date.now() + 120_000;
  const q = async (cmd, argv) => (await run(cmd, argv, { cwd: o.out, env: process.env, log: sink, deadline: dl, keepStdout: true })).stdout.trim();
  const version = await q(process.execPath, [cliEntry, 'version']);
  const reqs = await q(process.execPath, [cliEntry, 'requirements']);
  let commit = o.cliCommit;
  if (!commit) commit = (await q('git', ['-C', cliDir, 'rev-parse', 'HEAD'])) || null;
  const uv = (await q('sh', ['-c', 'command -v uv || true'])) !== '';
  const pyExe = process.env.CORPUS_PYTHON || 'python3';
  const runner = {
    lane: o.lane,
    image_os: process.env.ImageOS ?? null,
    image_version: process.env.ImageVersion ?? null,
    runner_os: process.env.RUNNER_OS ?? null,
    runner_arch: process.env.RUNNER_ARCH ?? null,
    platform: `${platform()} ${release()} ${arch()}`,
    os_version: platform() === 'darwin' ? await q('sw_vers', ['-productVersion']) : await q('sh', ['-c', '. /etc/os-release 2>/dev/null && echo "$PRETTY_NAME" || true']),
    node: process.version,
    npm: await q('npm', ['--version']),
    python: await q(uv ? 'uv' : pyExe, uv ? ['run', '--no-project', '--python', process.env.CORPUS_PY_VERSION || '3.12', 'python', '--version'] : ['--version']),
    docker: await q('sh', ['-c', "docker version --format '{{.Server.Version}}' 2>/dev/null || true"]),
  };
  return {
    cliEntry,
    cli: { commit, version, entry_sha256: sha256File(cliEntry), requirements_sha256: sha256Text(reqs) },
    spec: { version: (/\(MWS ([0-9.]+)\)/.exec(version) ?? [])[1] ?? null, requirements: reqs.split('\n').filter((l) => /^MWS-/.test(l.trim())).length },
    runner,
    github: process.env.GITHUB_RUN_ID
      ? { repository: process.env.GITHUB_REPOSITORY, run_id: process.env.GITHUB_RUN_ID, run_attempt: process.env.GITHUB_RUN_ATTEMPT, sha: process.env.GITHUB_SHA, workflow: process.env.GITHUB_WORKFLOW, event: process.env.GITHUB_EVENT_NAME }
      : null,
    python: { uv, exe: pyExe, version: process.env.CORPUS_PY_VERSION || '3.12' },
    runId: (process.env.GITHUB_RUN_ID ?? `l${Date.now().toString(36)}`) + `s${o.shard}`,
    keepWork: process.env.CORPUS_KEEP_WORK === '1',
  };
}

async function main() {
  let o;
  let failed = false;
  say(LABEL);
  try {
    o = args(process.argv.slice(2));
    mkdirSync(join(o.out, '_shard'), { recursive: true });
    o.work = resolve(o.work ?? join(o.out, '..', `work-${o.shard}`));
    mkdirSync(o.work, { recursive: true });
    const raw = readFileSync(o.targets);
    if (o.consumeTargets) rmSync(o.targets, { force: true }); // no clear-text list on disk while targets run
    const list = JSON.parse(raw.toString('utf8'));
    if (list.format !== TARGETS_FORMAT) throw new HarnessError('the target list has another format');
    const mine = list.targets
      .filter((t) => (t.lane ?? 'ci') === o.lane && t.enabled !== false)
      .filter((t) => !o.only || o.only.includes(t.id))
      .filter((_, i) => i % o.shards === o.shard - 1);
    const ctx = await context(o);
    ctx.defaults = list.defaults ?? {};
    const shard = { format: RUN_FORMAT, label: LABEL, lane: o.lane, shard: o.shard, shards: o.shards, targets_list_sha256: createHash('sha256').update(raw).digest('hex'), targets_list_updated: list.updated ?? null, cli: ctx.cli, spec: ctx.spec, runner: ctx.runner, github: ctx.github, started: now(), targets: [] };
    for (const t of mine) {
      const m = await runTarget(t, o, ctx);
      shard.targets.push({ id: t.id, status: m.status, cli_exit: m.cli_exit, public_exit: m.public_exit, results: m.results.map((r) => r.sha256) });
      say(`run finished, exit ${m.public_exit}`);
      if (m.public_exit !== 0) failed = true;
    }
    shard.ended = now();
    writeFileSync(join(o.out, '_shard', 'shard.json'), JSON.stringify(shard, null, 2) + '\n');
  } catch (e) {
    // A harness failure: the message may name a target, so it goes to a file, not to the log.
    try {
      const out = o?.out ?? '.';
      mkdirSync(join(out, '_shard'), { recursive: true });
      writeFileSync(join(out, '_shard', 'harness-error.txt'), `${now()}\n${e?.stack ?? e}\n`);
    } catch {}
    say('run finished, exit 125');
    failed = true;
  }
  process.exitCode = failed ? 1 : 0;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  // An unexpected rejection must not print a stack (it can carry a target's name).
  process.on('uncaughtException', () => { say('run finished, exit 125'); process.exit(1); });
  process.on('unhandledRejection', () => { say('run finished, exit 125'); process.exit(1); });
  main();
}
